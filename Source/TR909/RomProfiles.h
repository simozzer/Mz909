// What the ROMs' stand-ins are made to sound like: a description of each sound, measured
// from recordings of a 909-style machine (a Behringer RD-9) and written down as numbers.
// No audio is kept - Roms.cpp generates new sound from noise and sine waves and shapes it
// to these descriptions.
//
// Each profile is:
//  - seconds     how long the sample is
//  - times       the moments described, in seconds from the hit
//  - levels      at each moment, the energy in each of Roms.cpp's 18 bands, in dB re the
//                loudest; for the hihats, with the VCA's fall divided back out, so it is
//                the sample as it goes into the VCA
//  - onset       the first 40 ms, a millisecond at a time, in dB re 30-40 ms
//  - partials    steady pitches: hertz, and how far each stands above the noise round it
//                (dB) early, in the middle and late in the sound
//
// Generated by measuring; not meant to be edited by hand.
//

